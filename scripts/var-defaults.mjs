/**
 * Extract every --apex-* variable's default from the library stylesheet.
 *
 * The fallback in `var(--apex-x, FALLBACK)` IS the default — that is the whole
 * point of the indirection. Retyping 288 of them into the docs by hand is how a
 * reference goes stale: the CSS moves, the table does not, and nobody notices
 * because nothing fails. Reading them from source cannot drift.
 *
 *   node scripts/var-defaults.mjs
 *
 * Writes src/var-defaults.ts. Re-run it after changing the stylesheet; the
 * coverage test fails if the two disagree.
 */
import { readFileSync, writeFileSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, resolve } from 'path';

const here = dirname(fileURLToPath(import.meta.url));
const STYLES = resolve(here, '../../apex-ui/src/styles/apex-ui.css');
/* The raw palette lives here and is imported by the stylesheet above. Reading
   only the stylesheet made six palette variables look read-but-never-set. */
const TOKENS = resolve(here, '../../apex-ui/src/styles/tokens.css');
const OUT = resolve(here, '../src/var-defaults.ts');

/**
 * Scan one `var(` and return its name, its fallback and where it ended.
 * Written by hand rather than with a regex because a fallback can itself be
 * `color-mix(in srgb, var(--x) 12%, transparent)` — nested parens and commas
 * that no flat pattern gets right.
 */
function readVar(css, at) {
  let depth = 0;
  let i = at + 4;
  let comma = -1;
  for (; i < css.length; i++) {
    const c = css[i];
    if (c === '(') depth++;
    else if (c === ')') { if (!depth) break; depth--; }
    else if (c === ',' && !depth && comma < 0) comma = i;
  }
  const end = comma < 0 ? i : comma;
  return {
    name: css.slice(at + 4, end).trim(),
    fallback: comma < 0 ? '' : css.slice(comma + 1, i).trim(),
    next: i + 1,
  };
}

const css = readFileSync(STYLES, 'utf8');
const tokens = readFileSync(TOKENS, 'utf8');
const found = new Map();

for (let i = css.indexOf('var(--apex-'); i >= 0; i = css.indexOf('var(--apex-', i + 1)) {
  const { name, fallback } = readVar(css, i);
  if (!name.startsWith('--apex-')) continue;
  // First reading wins, and a real fallback beats an empty one: a variable is
  // usually read once with its default and again in a state rule without.
  if (!found.has(name) || (!found.get(name) && fallback)) found.set(name, fallback);
}

/**
 * The other half. A variable with no inline fallback is not undefaulted — it is
 * declared on a rule instead (`.apex-field { --apex-pop-bg: var(--bg-elevated) }`).
 * Several declarations means it varies by size or severity, which is worth
 * saying rather than picking one and calling it the default.
 */
const declared = new Map();
const palette = new Set();
for (const m of (css + tokens).matchAll(/(--apex-[a-z0-9-]+)\s*:\s*([^;}]+)/g)) {
  const list = declared.get(m[1]) || [];
  list.push(m[2].trim());
  declared.set(m[1], list);
}
/* Palette entries are raw colour ramps, not per-component knobs. They belong
   on the Theming page, so mark them rather than listing them beside
   --apex-picker-thumb-size as if they were the same kind of thing. */
for (const m of tokens.matchAll(/(--apex-[a-z0-9-]+)\s*:/g)) palette.add(m[1]);

const dead = [];
const varies = [];
found.forEach((fallback, name) => {
  if (fallback) return;
  const decls = declared.get(name);
  if (!decls) { dead.push(name); return; }
  found.set(name, decls[0]);
  // Distinct values, not just repeats of the same one.
  if (new Set(decls).size > 1) varies.push([name, new Set(decls).size]);
});

const rows = [...found.entries()].sort(([a], [b]) => a.localeCompare(b));
const body = rows.map(([k, v]) => `  '${k}': ${JSON.stringify(v)},`).join('\n');

const paletteList = [...palette].filter((p) => found.has(p)).sort();

writeFileSync(OUT, `/* GENERATED by scripts/var-defaults.mjs — do not edit by hand.
 *
 * Each variable's default, read from apex-ui.css and tokens.css. The fallback
 * in var(--x, FALLBACK) is the default; where a variable is declared on a rule
 * instead, the base declaration is used. Re-run the script after changing
 * either stylesheet — the coverage test fails when they disagree.
 */
export const VAR_DEFAULTS: Record<string, string> = {
${body}
};

/** Every --apex-* the stylesheets read, so coverage can be checked both ways. */
export const ALL_VARS = Object.keys(VAR_DEFAULTS);

/** Raw palette ramps from tokens.css — theming, not per-component styling. */
export const PALETTE_VARS = ${JSON.stringify(paletteList, null, 2).replace(/\n/g, '\n')};

/** Vary by size or severity; the default above is the base declaration. */
export const VARIES_BY_STATE = ${JSON.stringify(varies.map(([k]) => k).sort(), null, 2)};
`);

console.log(`wrote ${rows.length} variables to src/var-defaults.ts`);

if (varies.length) {
  console.log(`\n${varies.length} vary by size or severity — the value written is the base one:`);
  varies.forEach(([k, n]) => console.log(`  ${k}  (${n} distinct declarations)`));
}
if (dead.length) {
  console.log(`\n${dead.length} READ BUT NEVER SET — these resolve to nothing:`);
  dead.forEach((k) => console.log('  ' + k));
}
